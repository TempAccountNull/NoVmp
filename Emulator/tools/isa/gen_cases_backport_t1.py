def b(bs, inputs="", exp=None, note=None):
    if len(bs) >= 64:
        raise SystemExit("snippet too long: %d bytes" % len(bs))
    line = ".byte " + ", ".join("0x%02x" % x for x in bs)
    if inputs:
        line += " | " + inputs
    if exp is not None:
        line += " " + exp
    if note:
        line += " # " + note    # "known deviation: NAME" or "host state: REASON"
    out.append(line)


