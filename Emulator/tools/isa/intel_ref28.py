#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""
intel_ref28.py (ledger U1247, AVX512ER, U994): expected values and flags of VRCP28PS/PD/SS/SD,
VRSQRT28PS/PD/SS/SD and VEXP2PS/PD for ref_xeonphi.py.

Since U1247 (user decisions 2026-10-11) the emulator computes these forms with Intel's reference implementation
(article 671685, RECIP28EXP2.c; the SDM's "numerically exact implementation of VRCP28xx / VRSQRT28xx / VEXP2xx")
with one documented choice: VEXP2PD of x in [1024 - 2^-25, 1024) (0x408FFFFFFFFC0000 .. 0x408FFFFFFFFFFFFF)
returns 0x7FEFFFFFE0000000 without a flag (the reference's +0 there is a signed overflow of "tmp.u << 29";
SDM 092 Vol2D 8-8 requires a result within 2^-23 of 2^x; SDM gap, user decision 2026-10-11). The expected values
come from Intel's ORIGINAL RECIP28EXP2.c, compiled by path outside the repository (the AMB-2 harness amb2ref.exe,
"list" mode), never from the emulator: Emulator/data/intel_ref28_values.txt holds that program's OUTPUT
(routine, input, result, flags) for exactly the inputs the case files use - data, not code.

Collect mode: INTEL_REF28_COLLECT=FILE appends unknown inputs ("ROUTINE X") and returns placeholders.
"""
import os

HERE = os.path.dirname(os.path.abspath(__file__))
PATH = os.path.normpath(os.path.join(HERE, "..", "..", "data", "intel_ref28_values.txt"))
FORMS = ("RCP28S", "RCP28D", "RSQRT28S", "RSQRT28D", "EXP2S", "EXP2D")
EXP2D_GAP = (0x408FFFFFFFFC0000, 0x408FFFFFFFFFFFFF)     # [1024 - 2^-25, 1024)
EXP2D_GAP_RESULT = 0x7FEFFFFFE0000000                     # the largest finite 24-bit result, no flag

_tab = None
_collect = os.environ.get("INTEL_REF28_COLLECT")
_seen = set()


def load():
    global _tab
    if _tab is None:
        _tab = {}
        if os.path.exists(PATH):
            for line in open(PATH):
                t = line.split()
                if len(t) == 4 and t[0] in FORMS:
                    _tab[(t[0], int(t[1], 16))] = (int(t[2], 16), int(t[3], 16))
    return _tab


def value(form, x):
    """(result, MXCSR flag bits) of one element: Intel's reference, except the EXP2D SDM-gap choice"""
    if form == "EXP2D" and EXP2D_GAP[0] <= x <= EXP2D_GAP[1]:
        return EXP2D_GAP_RESULT, 0
    k = (form, x)
    tab = load()
    if k in tab:
        return tab[k]
    if _collect:
        if k not in _seen:
            _seen.add(k)
            with open(_collect, "a") as fh:
                fh.write("%s %X\n" % k)
        return 0, 0
    raise KeyError("intel_ref28_values.txt has no %s X %X: rerun the AMB-2 harness (collect mode)" % k)


def name_of(op, bits):
    return {"rcp28": "RCP28", "rsqrt28": "RSQRT28", "exp2": "EXP2"}[op] + ("S" if bits == 32 else "D")


# the unit tests' lanes (test_x86.c xp_ / amb2_ blocks), as macros in x86_er_ref.inc
UNIT_KEYS = [("EXP2D", 0x3FE0000000000000), ("EXP2D", 0x408FFFFFFFFBFFFF), ("RCP28S", 0x40400000)]


def macro(form, x):
    return "ERREF_%s_%0*X" % (form, 8 if form.endswith("S") else 16, x)


if __name__ == "__main__":
    import sys
    if "--need-unit" in sys.argv:
        with open(sys.argv[sys.argv.index("--need-unit") + 1], "a") as fh:
            for k in UNIT_KEYS:
                fh.write("%s %X\n" % k)
    elif "--unit-inc" in sys.argv:
        out = sys.argv[sys.argv.index("--unit-inc") + 1]
        lines = ["/* x86_er_ref.inc - generated by Emulator/tools/isa/intel_ref28.py --unit-inc (ledger U1247); do not edit.",
                 "   Intel reference values (Intel's original RECIP28EXP2.c, article 671685) of unit-test lanes:",
                 "   ERREF_<routine>_<input>. */"]
        for f, x in UNIT_KEYS:
            r, fl = value(f, x)
            lines.append("#define %s 0x%X%s" % (macro(f, x), r, "u" if f.endswith("S") else "ULL"))
        open(out, "w", newline="\r\n").write("\n".join(lines) + "\n")
        print("wrote", out)
    else:
        print(__doc__)
