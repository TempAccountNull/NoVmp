#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""
intel_ref14.py (ledger U1245): expected values of VRCP14PS/PD/SS/SD and VRSQRT14PS/PD/SS/SD for the case
generators (ref_rcp.py, ref_amb2.py, ref_evex_m2_cvt.py).

Since U1245 (user decision 2026-10-11) the emulator computes these forms with Intel's reference implementation
(article 671685, recip14.c; the SDM's "numerically exact implementation of VRCP14xx / VRSQRT14xx"), with one
SDM-wins change (RCP14D of -2^1023 under FTZ: -0). The expected values therefore come from Intel's ORIGINAL
recip14.c, compiled by path outside the repository (the AMB-2 agent harness, amb2ref.exe "list" mode), never
from the emulator: Emulator/data/intel_ref14_values.txt holds that program's OUTPUT (form, MXCSR DAZ/FTZ bits,
input, result) for exactly the inputs the case files use. It contains no code. The documented requirements of
every value are checked independently by ref_amb2.py --selftest (bound, special-case tables, DAZ / FTZ).

Collect mode: with the environment variable INTEL_REF14_COLLECT=FILE an unknown input is appended to FILE
("FORM MXCSR X") and a placeholder returned, so a generator run lists the inputs the harness must evaluate.
"""
import os

HERE = os.path.dirname(os.path.abspath(__file__))
PATH = os.path.normpath(os.path.join(HERE, "..", "..", "data", "intel_ref14_values.txt"))
FORMS = ("RCP14S", "RCP14D", "RSQRT14S", "RSQRT14D")
# the four SDM-wins inputs (the reference returns +0, the SDM a zero of the operand's sign)
SDM_WINS = {("RCP14D", 0x8000, 0xFFE0000000000000), ("RCP14D", 0x8040, 0xFFE0000000000000)}

_tab = None
_collect = os.environ.get("INTEL_REF14_COLLECT")
_seen = set()


def key_mx(mxcsr):
    """the reference routines read MXCSR bits 6 (DAZ) and 15 (FTZ) only"""
    return mxcsr & 0x8040


def load():
    global _tab
    if _tab is None:
        _tab = {}
        if os.path.exists(PATH):
            for line in open(PATH):
                t = line.split()
                if len(t) == 4 and t[0] in FORMS:
                    _tab[(t[0], int(t[1], 16), int(t[2], 16))] = int(t[3], 16)
    return _tab


def value(form, x, mxcsr):
    """Intel reference result (with the SDM-wins signed zero) for one element"""
    k = (form, key_mx(mxcsr), x)
    if k in SDM_WINS:
        return 0x8000000000000000
    tab = load()
    if k in tab:
        return tab[k]
    if _collect:
        if k not in _seen:
            _seen.add(k)
            with open(_collect, "a") as fh:
                fh.write("%s %04X %X\n" % k)
        return 0
    raise KeyError("intel_ref14_values.txt has no %s MXCSR %04X X %X: rerun the AMB-2 harness (collect mode)" % k)


def name_of(op, bits):
    return ("RCP14" if op == "rcp" else "RSQRT14") + ("S" if bits == 32 else "D")


# U1245: the unit tests' approximation lanes (test_x86.c rc_ block), as macros in x86_rcp14_ref.inc
UNIT_KEYS = [("RCP14S", m, x) for m in (0x0000,) for x in (0x00200001, 0x7F7FFFFF, 0x7E800001, 0x807FFFFF,
                                                          0x40400000, 0x3FC00000, 0x7ED38264)] + \
            [("RCP14S", 0x0040, x) for x in (0x7F7FFFFF, 0x7E800001, 0x40400000, 0x3FC00000)] + \
            [("RCP14S", 0x8000, x) for x in (0x00200001, 0x807FFFFF, 0x40400000, 0x3FC00000)] + \
            [("RSQRT14D", m, x) for m in (0x0000, 0x0040) for x in (0x4000000000000000, 0x7FEFFFFFFFFFFFFF)] + \
            [("RCP14D", 0x0000, 0x7FD90976DE723B2F)]


def macro(form, mx, x):
    return "RCREF_%s_%04X_%0*X" % (form, mx, 8 if form.endswith("S") else 16, x)


if __name__ == "__main__":
    import sys
    if "--need-unit" in sys.argv:
        with open(sys.argv[sys.argv.index("--need-unit") + 1], "a") as fh:
            for k in UNIT_KEYS:
                fh.write("%s %04X %X\n" % k)
    elif "--unit-inc" in sys.argv:
        out = sys.argv[sys.argv.index("--unit-inc") + 1]
        lines = ["/* x86_rcp14_ref.inc - generated by Emulator/tools/isa/intel_ref14.py --unit-inc (ledger U1245); do not edit.",
                 "   Intel reference values (Intel's original recip14.c, article 671685) of the unit tests' VRCP14 /",
                 "   VRSQRT14 approximation lanes: RCREF_<routine>_<MXCSR DAZ/FTZ bits>_<input>. */"]
        for k in UNIT_KEYS:
            lines.append("#define %s 0x%X%s" % (macro(*k), value(k[0], k[2], k[1]), "u" if k[0].endswith("S") else "ULL"))
        open(out, "w", newline="\r\n").write("\n".join(lines) + "\n")
        print("wrote", out)
    else:
        print(__doc__)
